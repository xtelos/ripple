"""The JDK's own types and what they have: java.base and java.compiler, from ripple/data/java_jdk.txt.

ripple has no classpath, so a repo type that extends a type from outside the repo may inherit a member that no source of
the repo shows. This table is what ripple knows of such a supertype. It is generated by bench/java_jdk/generate.py from the
class files of EVERY released JDK from 8 through 27 (the twenty GA feature releases, each with its exact version in the
file's header), because the repo may be built against any of them and ripple cannot tell which. Every fact is merged across
the JDKs in the one direction it is used safely.

THE HORIZON. The table covers JDK 8 through 27. A repo built with a later JDK may meet a member, a supertype, a field or a
member type that no JDK of the table has (JDK 26 gave `java.lang.Process` an `AutoCloseable` supertype and a `close()`),
and ripple cannot prove from the repo that it does not. That is an assumption of the table, not a fact: the first GA after
27 needs a regeneration (tests/test_java_jdk.py pins the header's newest JDK, so it fails until one is made).

A type that is NOT in the table is UNKNOWN, never "declares nothing": jdk_type returns None for it, and a caller must treat
that as "may declare anything, may be a subtype of anything". The generator leaves a type out when it cannot know all of it
(a supertype it cannot read, or one that is not itself in the table), so a row is only ever complete. The ONE reader that
takes a missing row as proof is java_resolver.no_repo_instance ("no table type below this `ctor=no` class can be extended"), so
the generator refuses to run when a type it leaves out is below such a class, and the loader refuses a truncated file (below).

A table the loader cannot trust is refused whole (JdkTable.problem): the header carries the row count (`# rows: N`) and a
file that was cut, or whose count or columns disagree, has no type in it at all. The resolver says so in the graph's
`unread` notes (java_indexer.index_files) and treats every type from outside the repo as unknown.

What a row holds (one line per type, `name | kind | final | ctor=.. | jdk=.. | supers=.. | types=.. | fields=.. | methods=..`):

  name      the canonical name: `java.util.Map.Entry`, never `java.util.Map$Entry` (the nesting comes from the class file's
            InnerClasses entry, so a `$` in a name is part of the name).
  kind      class, interface, enum or annotation.
  final     True when the type is final in EVERY JDK that has it (the intersection). "T is final, so no repo type is an
            instance of it" is the one use, and a type that is open in even one JDK may have a repo subtype there.
  ctor      `yes` when the type declares a public or protected constructor in ANY of the JDKs that have it (the union), `no`
            when it does in none, `na` for an interface or an annotation. "T has no accessible constructor, so no repo class
            extends it directly" is the one use, and only `no` proves it: `java.util.Arrays` is final from JDK 21 only, but has had
            a private constructor throughout, so it is `no`; a type that is `yes` in one JDK may have a repo subclass there. On
            JdkType it is `ctor`: True, False, or None for `na`. A constructor is still not a member a subtype inherits.
  jdks      the JDKs that have the type. A type only some have is described over those.
  supers    every type above this one, transitively (java.lang.Object left out) that a repo can name, as the UNION over the
            JDKs: `java.util.List` lists SequencedCollection (JDK 21 and up) though JDK 8's List has no such supertype.
            "T is not a subtype of U" is proven only when U is not in this set (and T is not U).
  types     the simple names of the public and protected member types that T declares or inherits (the UNION):
            `Entry` for a Map, and `SimpleEntry` for an AbstractMap. A name in the set may hide a type of the same name
            from an outer scope or an import; a name that is not in it cannot.
  fields    the public and protected fields T declares or inherits, static ones too (the UNION): `Writer.lock`,
            `FilterInputStream.in`. A field name that is not in the set is not T's.
  methods   the public and protected methods T declares or inherits, static ones too (the UNION), name -> the numbers of
            arguments a call may pass. A name that is not in the set, or a count of arguments that the entry does not admit,
            is not a method of T's. Interface members are public. Static methods of an interface are included although a
            class does not inherit them (JLS 8.4.8): that only ever makes a call "may declare", never wrongly proven absent.

java.lang.Object's methods are in a row only for Object itself and for a type that declares one again (`Enum.toString`):
ripple checks Object's members on their own (java_resolver.OBJECT_SIGNATURES), as it did for the hand tables this replaced.
A constructor is not a member that a subtype inherits: it is in no `methods` entry, only in the `ctor` column.

Arities. A method's entry is `Arities`: `exact`, the numbers of parameters of its overloads that are not varargs, and
`minimum`, set when some overload is varargs with k fixed parameters before it, which is "k or more arguments". So
`PrintStream.printf(String, Object...)` and `printf(Locale, String, Object...)` are one entry with minimum 1: a call
with 1, 2 or 20 arguments may be printf's. `admits(n)` answers that; it is the only question to ask, to know whether a call
may be a method's. "Declares exactly no parameters" (a repo `foo()` overrides it) is another question: `0 in exact`, since a
varargs `foo(Object...)` admits 0 arguments and is not the signature `foo()`. In the file an entry is written `printf/1+`, `write/1,3`, `of/0+` (an exact count, then at most one `k+`).

The file is read lazily, on the first lookup: `import ripple` and every run that never indexes Java never open it.
"""

from __future__ import annotations

import functools
from dataclasses import dataclass
from importlib import resources

DATA_FILE = "data/java_jdk.txt"


@dataclass(frozen=True)
class Arities:
    """The numbers of arguments a method name may be called with: `exact`, and any n >= `minimum` when a varargs overload exists."""

    exact: frozenset[int]
    minimum: int | None = None

    def admits(self, n: int) -> bool:
        return n in self.exact or (self.minimum is not None and n >= self.minimum)

    @classmethod
    def parse(cls, text: str) -> Arities:
        exact: set[int] = set()
        minimum: int | None = None
        for part in text.split(","):
            if part.endswith("+"):
                minimum = int(part[:-1])
            else:
                exact.add(int(part))
        return cls(frozenset(exact), minimum)


@dataclass(frozen=True)
class JdkType:
    name: str
    kind: str
    final: bool
    ctor: bool | None  # True: some JDK gives it a public or protected constructor; False: none does; None: an interface or annotation
    jdks: tuple[int, ...]
    supers: frozenset[str]
    member_types: frozenset[str]
    fields: frozenset[str]
    methods: dict[str, Arities]

    def may_declare_method(self, name: str, n: int | None = None) -> bool:
        """Whether the type declares or inherits a method `name` (taking n arguments, when n is given)."""
        arities = self.methods.get(name)
        return arities is not None and (n is None or arities.admits(n))

    def may_declare_field(self, name: str) -> bool:
        return name in self.fields

    def may_declare_member_type(self, name: str) -> bool:
        return name in self.member_types

    def may_be_instance_of(self, name: str) -> bool:
        """Whether a value of this type may also be of the type `name` (a canonical name): it is that type or is below it."""
        return name == self.name or name in self.supers


_CTOR = {"ctor=yes": True, "ctor=no": False, "ctor=na": None}


def _list(text: str) -> frozenset[str]:
    return frozenset(filter(None, text.split(",")))


def parse_row(line: str) -> JdkType:
    name, kind, final, ctor, jdks, supers, types, fields, methods = line.rstrip("\n").split(" | ")
    return JdkType(
        name, kind, final == "final", _CTOR[ctor], tuple(int(j) for j in jdks.removeprefix("jdk=").split(",")),
        _list(supers.removeprefix("supers=")), _list(types.removeprefix("types=")), _list(fields.removeprefix("fields=")),
        {entry.split("/")[0]: Arities.parse(entry.split("/")[1]) for entry in methods.removeprefix("methods=").split()},
    )


ROW_COLUMNS = 9


class JdkTable:
    """A table text: the header lines and the rows, each row parsed on its first lookup.

    A table the loader cannot trust is REFUSED WHOLE, never read in part: `problem` says why, and then no type is in it, so
    every type is unknown (`get` is None for all, `names` is empty). The checks: the header `# rows: N` is there once and N
    is the number of rows, every row has its nine columns, no name is in it twice, and the text ends in a newline. One of
    these fails for a file cut anywhere, which matters because a missing row is "unknown" for a type of the repo's
    supertypes but, for `no_repo_instance` (java_resolver.py), a missing row is a proof."""

    def __init__(self, text: str) -> None:
        self.headers: list[str] = []
        self._lines: dict[str, str] = {}
        self._rows: dict[str, JdkType] = {}
        self.problem: str | None = None
        lines = 0
        short = twice = None
        for line in text.splitlines():
            if line.startswith("#"):
                self.headers.append(line[1:].strip())
            elif line:
                lines += 1
                name = line.split(" | ", 1)[0]
                if line.count(" | ") != ROW_COLUMNS - 1 and short is None:
                    short = name
                if name in self._lines and twice is None:
                    twice = name
                self._lines[name] = line
        why = self._why_refused(text, lines, short, twice)
        if why is not None:
            self.problem = f"the JDK table ({DATA_FILE}) is refused: {why}; every type of the JDK is treated as unknown"
            self._lines = {}

    def _why_refused(self, text: str, lines: int, short: str | None, twice: str | None) -> str | None:
        counts = [header for header in self.headers if header.startswith("rows:")]
        if not counts:
            return "it has no row count header (`# rows: N`)"
        if len(counts) > 1:
            return "it has more than one row count header"
        try:
            expected = int(counts[0].partition(":")[2])
        except ValueError:
            return f"its row count header ({counts[0]!r}) is not a number"
        if expected != lines:
            return f"its header counts {expected} rows and the file has {lines} (truncated or edited by hand)"
        if not text.endswith("\n"):
            return "the file does not end in a newline (truncated inside its last row)"
        if short is not None:
            return f"the row for {short} does not have its {ROW_COLUMNS} columns"
        if twice is not None:
            return f"{twice} is in it twice"
        return None

    def get(self, name: str) -> JdkType | None:
        row = self._rows.get(name)
        if row is None:
            line = self._lines.get(name)
            if line is None:
                return None
            row = self._rows[name] = parse_row(line)
        return row

    def __contains__(self, name: str) -> bool:
        return name in self._lines

    def __len__(self) -> int:
        return len(self._lines)

    def names(self) -> list[str]:
        return sorted(self._lines)


@functools.lru_cache(maxsize=1)
def table() -> JdkTable:
    return JdkTable(resources.files("ripple").joinpath(DATA_FILE).read_text(encoding="utf-8"))


def refusal() -> str | None:
    """Why the table was refused (see JdkTable), or None when it is whole or was not needed: this never opens the file, so a
    run that looked nothing up has nothing to say. (Any lookup reads the table, and a refused one answers None to all.)"""
    return table().problem if table.cache_info().currsize else None


def jdk_type(name: str) -> JdkType | None:
    """The row for a type by canonical name, or None: not in the table, so nothing about it is known."""
    return table().get(name)
