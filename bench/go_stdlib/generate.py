"""Write ripple/go_stdlib.py: what the Go standard library's own source says each exported name is.

Run by hand, like bench/go_oracle/generate.py; it needs a Go toolchain with its GOROOT source (no network). ripple reads the
result and never needs Go.

    python bench/go_stdlib/generate.py            (GO=/path/to/go to name the toolchain)

main.go type-checks every importable standard library package from source for one GOOS/GOARCH; this runs it for every
platform `go tool dist list` names (CGO off) and merges them so that a name counts as a function, a method or a function-typed
field only when no platform says otherwise:
  - FUNCS: a name that is a func declaration on every platform that has it. A variable that holds a function (`flag.Usage`),
    a constant and a type are not in it.
  - TYPES: per exported type, (kind, methods, function-typed fields). A name that is a function-typed field on any
    platform is not a method. A type that is an interface on one platform and not on another is an interface. A method
    of a struct that is promoted through an embedded interface is left out (the method that runs is the dynamic
    value's, so it is not proven the library's).
A name in neither list is not proven to be either, and ripple calls it unresolved.
"""

from __future__ import annotations

import json
import os
import shutil
import subprocess
import sys
import tempfile
import textwrap
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

HERE = Path(__file__).resolve().parent
OUTPUT = HERE.parent.parent / "ripple" / "go_stdlib.py"
UNSAFE_FUNCS = "Add Alignof Offsetof Sizeof Slice SliceData String StringData"  # package unsafe has no source to read


def go_binary() -> str:
    found = os.environ.get("GO") or shutil.which("go")
    if not found:
        sys.exit("generate.py needs a Go toolchain: put go on PATH or set GO")
    return found


def run_platform(program: str, go: str, platform: str) -> dict:
    goos, goarch = platform.split("/")
    env = dict(os.environ, GOOS=goos, GOARCH=goarch, CGO_ENABLED="0", PATH=str(Path(go).parent) + os.pathsep + os.environ["PATH"])
    done = subprocess.run([program], capture_output=True, text=True, env=env)
    if done.returncode:
        sys.exit(f"the table program failed for {platform}:\n{done.stderr}")
    return json.loads(done.stdout)


def merge(runs: list[dict]) -> tuple[dict[str, set[str]], dict[str, dict[str, tuple[str, set[str], set[str]]]]]:
    funcs: dict[str, set[str]] = {}
    other: dict[str, set[str]] = {}
    kinds: dict[tuple[str, str], set[str]] = {}
    methods: dict[tuple[str, str], set[str]] = {}
    fields: dict[tuple[str, str], set[str]] = {}
    for run in runs:
        for path, info in run.items():
            funcs.setdefault(path, set()).update(info["funcs"])
            other.setdefault(path, set()).update(info["other"])
            for name, t in info["types"].items():
                kinds.setdefault((path, name), set()).add(t["k"])
                methods.setdefault((path, name), set()).update(t["m"])
                fields.setdefault((path, name), set()).update(t["f"])
    final_funcs = {path: names - other[path] for path, names in funcs.items()}
    final_funcs["unsafe"] = set(UNSAFE_FUNCS.split())
    unsafe_types = {"Pointer": ("o", set(), set())}  # unsafe.Pointer(x) is a conversion
    final_types: dict[str, dict[str, tuple[str, set[str], set[str]]]] = {}
    for (path, name), kind in sorted(kinds.items()):
        kind_of = "i" if "i" in kind else sorted(kind)[0] if len(kind) == 1 else "o"
        final_types.setdefault(path, {})[name] = (kind_of, methods[(path, name)] - fields[(path, name)], fields[(path, name)])
    final_types["unsafe"] = unsafe_types
    return final_funcs, final_types


def words(names: set[str], indent: str) -> str:
    """The names as adjacent string literals that wrap, which Python joins into one string."""
    chunks = textwrap.wrap(" ".join(sorted(names)), width=100 - len(indent) - 3, break_long_words=False)
    if not chunks:
        return '""'
    return ("\n" + indent).join(f'"{chunk} "' if i < len(chunks) - 1 else f'"{chunk}"' for i, chunk in enumerate(chunks))


def render(funcs: dict[str, set[str]], types: dict[str, dict[str, tuple[str, set[str], set[str]]]], version: str, platforms: list[str]) -> str:
    out = [
        f'"""What the Go standard library says each exported name is ({version}, {len(platforms)} platforms). Generated by',
        "bench/go_stdlib/generate.py from the library's own source: do not edit by hand.",
        "",
        "ripple does not read a package outside the repo, so for `pkg.F(x)` and `v.F(x)` it cannot tell a function or a method from a",
        "variable or a struct field that holds a function. For the standard library this table can: FUNCS holds the names that are func",
        "declarations on every platform, TYPES the exported methods and function-typed fields of each exported type. A name that is",
        'in neither is not proven to be one, and ripple calls it unresolved."""',
        "",
        "# package path -> its exported func declarations, space separated",
        "FUNCS = {",
    ]
    for path in sorted(funcs):
        if funcs[path]:
            out.append(f'    "{path}": (\n        {words(funcs[path], "        ")}\n    ),')
    out += ["}", "", "# package path -> type -> (kind: i interface, s struct, o other; methods; function-typed fields), names space separated", "TYPES = {"]
    for path in sorted(types):
        out.append(f'    "{path}": {{')
        for name, (kind, methods, fields) in sorted(types[path].items()):
            out.append(f'        "{name}": ("{kind}", (\n            {words(methods, "            ")}\n        ), (\n            {words(fields, "            ")}\n        )),')
        out.append("    },")
    out += ["}", "", "PACKAGES = frozenset(FUNCS) | frozenset(TYPES)  # the packages the table covers (a package of only variables and constants is not here)", ""]
    return "\n".join(out)


def main() -> None:
    go = go_binary()
    version = subprocess.run([go, "version"], capture_output=True, text=True).stdout.split()[2]
    platforms = subprocess.run([go, "tool", "dist", "list"], capture_output=True, text=True, check=True).stdout.split()
    with tempfile.TemporaryDirectory() as scratch:
        program = str(Path(scratch) / "table")
        build = subprocess.run([go, "build", "-o", program, "."], cwd=HERE, capture_output=True, text=True)
        if build.returncode:
            sys.exit(f"could not build the table program:\n{build.stderr}")
        with ThreadPoolExecutor(max_workers=os.cpu_count() or 4) as pool:
            runs = list(pool.map(lambda p: run_platform(program, go, p), platforms))
    funcs, types = merge(runs)
    OUTPUT.write_text(render(funcs, types, version, platforms))
    print("wrote", OUTPUT, f"({len(funcs)} packages, {sum(len(v) for v in funcs.values())} funcs, {sum(len(v) for v in types.values())} types)")


if __name__ == "__main__":
    main()
